local M = {}

local MODEL_ID = "AIR_910604_WW"
local MANUFACTURER = "lg"
local PROTOCOL_FAMILY = "thinq2_tlv"

-- Frames this handler recognises. Byte 7 (1-based) is the dialect marker:
-- 0xA7 is the purifier/dehumidifier dialect. 0x87 is the air-conditioner
-- dialect and is explicitly NOT claimed here -- see UNSUPPORTED below.
local DIALECT_A7 = 0xA7
local DIALECT_87 = 0x87

local TLV_BODY_START = 12   -- 1-based index of the first TLV byte
local TLV_TRAILER = 2       -- trailing checksum bytes, ignored on input

-- Tag -> logical field. Only tags this handler is confident about.
local TAGS = {
  [0x1f7] = "power",
  [0x1f9] = "mode",
  [0x1fa] = "fan_speed",
  [0x333] = "pm1",
  [0x334] = "pm25",
  [0x335] = "pm10",
  [0x240] = "air_quality_index",
  [0x241] = "odor_index",
  [0x221] = "error_code",
  [0x355] = "filter_remaining_hours",
  [0x356] = "filter_life_hours",
}

local MODES = {
  [13] = "clean_booster",
  [14] = "single_clean",
  [15] = "dual_clean",
  [16] = "auto",
}

local FAN_SPEEDS = {
  [2] = "low", [4] = "medium", [6] = "high", [7] = "turbo", [8] = "auto",
}

-- Explicit table rather than `value ~= 0`. The declarative Level-1 profile
-- for this same model enumerates {0,1}, and a truthiness test would silently
-- report an undocumented value (say 2) as "on" while the profile reported
-- "unknown". Keeping the two paths byte-for-byte equivalent is what makes the
-- cross-language contract test meaningful.
local POWER = {[0] = "off", [1] = "on"}

-- ---------------------------------------------------------------------------
-- TLV decoding
-- ---------------------------------------------------------------------------
-- Encoding, for reviewers who want to check this without a device:
--   tag  = (b0 << 2) | (b1 >> 6)                 -- 10-bit tag
--   lsel = (b1 >> 4) & 0x03                      -- 0 = inline nibble
--   value = (lsel == 0) and (b1 & 0x0f)
--           or big-endian integer over the next `lsel` bytes
-- Element width is 2 + lsel bytes.
local function parse_tlv(bytes, first, last)
  local out = {}
  local i = first
  while i <= last do
    if i + 1 > last then
      -- Truncated trailing element. Return what we decoded rather than
      -- discarding a frame that was otherwise fine; the caller decides.
      return out, true
    end
    local b0, b1 = bytes[i], bytes[i + 1]
    local tag = (b0 << 2) | (b1 >> 6)
    local lsel = (b1 >> 4) & 0x03
    local value
    if lsel == 0 then
      value = b1 & 0x0f
    else
      if i + 1 + lsel > last then
        return out, true
      end
      value = 0
      for k = 1, lsel do
        value = (value << 8) | bytes[i + 1 + k]
      end
    end
    out[#out + 1] = {tag = tag, value = value, width = 2 + lsel}
    i = i + 2 + lsel
  end
  return out, false
end

local function decode_fields(elements)
  local state = {}
  local unknown_tags = ualc.array({})
  for _, el in ipairs(elements) do
    local name = TAGS[el.tag]
    if name == nil then
      unknown_tags[#unknown_tags + 1] = string.format("0x%03x", el.tag)
    elseif name == "power" then
      state.power = POWER[el.value]
      if state.power == nil then
        state.power = "unknown"
        state.power_raw = el.value
      end
    elseif name == "mode" then
      -- Out-of-domain values are reported, not silently mapped. A value we
      -- have never seen on any unit is a finding, not a parse failure.
      state.mode = MODES[el.value]
      if state.mode == nil then
        state.mode = "unknown"
        state.mode_raw = el.value
      end
    elseif name == "fan_speed" then
      state.fan_speed = FAN_SPEEDS[el.value]
      if state.fan_speed == nil then
        state.fan_speed = "unknown"
        state.fan_speed_raw = el.value
      end
    else
      state[name] = el.value
    end
  end
  return state, unknown_tags
end

-- ---------------------------------------------------------------------------
-- Operations
-- ---------------------------------------------------------------------------

function M.describe()
  return {
    api_version = ualc.API_VERSION,
    manufacturer = MANUFACTURER,
    protocol_family = PROTOCOL_FAMILY,
    models = ualc.array({MODEL_ID}),
    -- Read-only by design; see the header note on build_outbound.
    operations = ualc.array({
      "describe", "identify", "parse_inbound", "decode_state",
      "describe_controls", "supported_commands", "validate_command",
      "is_ack_for",
    }),
    support_level = "DECODED",
    verification_source = "none",
    notes = "Decoder only. Synthetic fixtures. Never run against hardware.",
  }
end

function M.identify(args)
  local model = args.model_id
  if model == MODEL_ID then
    return {supported = true, model_id = MODEL_ID, confidence = "exact"}
  end
  -- Do NOT claim sibling models. Same ThinQ model id across regions has
  -- already been observed to differ in its mode enum, and a similar chip or
  -- cloud platform is not evidence of a shared local protocol.
  return {
    supported = false,
    model_id = model,
    reason = "this handler claims only " .. MODEL_ID,
  }
end

function M.supported_commands()
  -- Honest empty set: this handler cannot build a frame.
  return ualc.array({})
end

function M.describe_controls()
  return {
    readable = ualc.array({
      "power", "mode", "fan_speed", "pm1", "pm25", "pm10",
      "air_quality_index", "odor_index", "error_code",
      "filter_remaining_hours", "filter_life_hours",
    }),
    writable = ualc.array({}),
    enums = {
      mode = ualc.array({"clean_booster", "single_clean", "dual_clean", "auto"}),
      fan_speed = ualc.array({"low", "medium", "high", "turbo", "auto"}),
      power = ualc.array({"on", "off"}),
    },
  }
end

function M.validate_command(args)
  return {
    valid = false,
    reason = "this handler is read-only; no command encoding is verified",
    command = args.command,
  }
end

function M.is_ack_for()
  -- Cannot send, therefore cannot acknowledge.
  return false
end

function M.decode_state(args)
  return M.parse_inbound(args)
end

function M.parse_inbound(args)
  local hex = args.payload_hex
  if type(hex) ~= "string" then
    ualc.fail("INVALID_PARAMS", "payload_hex must be a string")
  end

  local ok, bytes = pcall(ualc.hex_to_bytes, hex)
  if not ok then
    ualc.fail("MALFORMED_FRAME", "payload_hex is not valid hex")
  end

  local n = #bytes
  if n < TLV_BODY_START + TLV_TRAILER then
    ualc.fail("MALFORMED_FRAME",
              "frame too short: " .. n .. " bytes, need at least "
              .. (TLV_BODY_START + TLV_TRAILER))
  end

  -- Envelope check: bytes 3..6 (1-based) are the fixed 04 00 00 00 prefix.
  if not (bytes[3] == 0x04 and bytes[4] == 0x00
          and bytes[5] == 0x00 and bytes[6] == 0x00) then
    ualc.fail("MALFORMED_FRAME", "missing 04 00 00 00 envelope prefix")
  end

  local dialect = bytes[7]
  if dialect == DIALECT_87 then
    ualc.fail("UNSUPPORTED_PROTOCOL_VERSION",
              "0x87 dialect belongs to another appliance class; "
              .. "this handler only decodes 0xA7")
  end
  if dialect ~= DIALECT_A7 then
    ualc.fail("UNSUPPORTED_PROTOCOL_VERSION",
              string.format("unknown dialect marker 0x%02x", dialect))
  end

  local elements, truncated = parse_tlv(bytes, TLV_BODY_START, n - TLV_TRAILER)
  if #elements == 0 then
    ualc.fail("MALFORMED_FRAME", "no decodable TLV elements")
  end

  local state, unknown_tags = decode_fields(elements)

  -- A full-state frame carries many tags; a change notification carries one
  -- or two. The host must not overwrite known values from a partial frame,
  -- so the distinction is reported rather than guessed at by the core.
  local partial = #elements < 6

  local result = {
    model_id = MODEL_ID,
    event_kind = "status",
    state = state,
    partial = partial,
  }
  if #unknown_tags > 0 then
    result.state.unknown_tag_count = #unknown_tags
  end
  if truncated then
    result.state.frame_truncated = true
  end
  return result
end

-- The checksum trailer is intentionally not verified. On real hardware the
-- Wi-Fi module validates it before the frame reaches us, and this project has
-- not independently confirmed the polynomial. Claiming a checksum check we
-- have not verified would be worse than skipping it openly.

return M
